import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type { AppJourney } from "../types.js";
import type { Tool, ToolContext, ToolFinding, ToolOutput } from "./types.js";

/**
 * Exports the project's journeys as test code the client can keep and run in their own CI: a
 * Playwright spec for the website (visit each page the crawl found, check it loads and has a title)
 * and, for a mobile app, an Appium / WebdriverIO script from the app journeys. The client is not
 * locked into GLV: they get real @playwright/test and Appium files. It only writes files, so it is safe.
 */

/** A Playwright spec that opens each page and checks it loads with a title. Pure, for tests. */
export function playwrightSpec(baseUrl: string, pages: string[]): string {
  const rel = (u: string) => {
    try {
      const url = new URL(u, baseUrl);
      return url.pathname + url.search;
    } catch {
      return u;
    }
  };
  const uniq = [...new Set(pages.map(rel))].slice(0, 100);
  const cases = uniq
    .map(
      (p) => `  test(${JSON.stringify(`loads ${p}`)}, async ({ page }) => {
    const res = await page.goto(${JSON.stringify(p)});
    expect(res?.status(), ${JSON.stringify(`${p} should not be an error`)}).toBeLessThan(400);
    await expect(page).toHaveTitle(/.+/);
  });`,
    )
    .join("\n\n");
  return `import { test, expect } from "@playwright/test";

// Generated by GLV testing-agent. Run: npx playwright test
// Set the base URL with: PLAYWRIGHT_BASE_URL=${baseUrl} npx playwright test
test.use({ baseURL: process.env.PLAYWRIGHT_BASE_URL || ${JSON.stringify(baseUrl)} });

test.describe("Smoke: pages load", () => {
${cases}
});
`;
}

/** A readable Appium/WebdriverIO script from app journeys. Pure, for tests. */
export function appiumSpec(appId: string, platform: string, journeys: AppJourney[]): string {
  const steps = (text: string) =>
    text
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter(Boolean)
      .map((l) => `    // ${l}\n    // TODO: driver.$("~<accessibility id>").click(); etc.`)
      .join("\n");
  const blocks = journeys
    .filter((j) => !j.off)
    .map(
      (j) => `  it(${JSON.stringify(j.name)}, async () => {
${steps(j.steps)}
  });`,
    )
    .join("\n\n");
  return `// Generated by GLV testing-agent — Appium + WebdriverIO (${platform}).
// npm i -D @wdio/cli appium; npx appium; then run with your wdio config.
// capabilities: { platformName: ${JSON.stringify(platform === "ios" ? "iOS" : "Android")}, "appium:app": "<path to build>", "appium:appPackage": ${JSON.stringify(appId)} }

describe(${JSON.stringify(appId)}, () => {
${blocks || "  it(\"opens the app\", async () => {\n    await driver.pause(2000);\n  });"}
});
`;
}

export const exportCodeTool: Tool = {
  id: "export-code",
  name: "Export tests as code",
  maker: "GLV Infotech (built in)",
  description:
    "Turns the project's journeys into test code the client can keep and run in their own CI: a Playwright spec that opens every page the crawl found (and checks it loads with a title), and, for a mobile app, an Appium / WebdriverIO script from the app journeys. Real, standard test files — no lock-in.",
  checks: ["A @playwright/test smoke spec for the website's pages", "An Appium / WebdriverIO script for a mobile app's journeys", "Standard files the client runs in their own CI"],
  products: ["website", "ecommerce", "webapp", "saas", "crm", "api"],
  category: "functional",
  safety: "safe",
  takes: "under a minute",
  licence: "GLV's own",
  homepage: "https://playwright.dev",
  signedIn: "public",
  async ready() {
    return null;
  },
  async run(ctx: ToolContext): Promise<ToolOutput> {
    const dir = path.join(ctx.outDir, "tests");
    await mkdir(dir, { recursive: true });
    const made: string[] = [];
    const reports: { file: string; label: string }[] = [];
    if (ctx.urls.length) {
      const spec = playwrightSpec(ctx.startUrl, ctx.urls);
      await writeFile(path.join(dir, "smoke.spec.ts"), spec);
      made.push(`Playwright spec for ${Math.min(ctx.urls.length, 100)} pages`);
      reports.push({ file: "tests/smoke.spec.ts", label: "Playwright smoke spec (@playwright/test)" });
    }
    if (ctx.app && ctx.appJourneys?.length) {
      const spec = appiumSpec(ctx.app.id, ctx.app.platform, ctx.appJourneys);
      await writeFile(path.join(dir, "app.e2e.ts"), spec);
      made.push(`Appium script for ${ctx.appJourneys.filter((j) => !j.off).length} journeys`);
      reports.push({ file: "tests/app.e2e.ts", label: "Appium / WebdriverIO script" });
    }
    if (!made.length) throw new Error("Nothing to export: no crawled pages and no app journeys were available for this project.");
    ctx.log(`Export: ${made.join("; ")}`);
    const findings: ToolFinding[] = [];
    return {
      findings,
      summary: [`Exported ${made.join(" and ")}. Download them below and run in your own CI.`],
      reports,
      tested: made.join("; "),
    };
  },
};
