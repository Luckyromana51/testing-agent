/** The ACR markdown document. `statuses` maps a criterion number to Supports/Partially/Does Not Support. Pure, for tests. */
export function vpatDocument(product: string, siteUrl: string, date: string, statuses: Record<string, { status: string; remarks: string }> = {}): string {
  const row = (n: string, name: string, level: string) => {
    const s = statuses[n] ?? { status: "Not Evaluated", remarks: "" };
    return `| ${n} ${name} (Level ${level}) | ${s.status} | ${s.remarks} |`;
  };
  return `# Accessibility Conformance Report (VPAT 2.5)

**Product:** ${product}
**Site:** ${siteUrl}
**Report date:** ${date}
**Standards:** WCAG 2.1 Level A and AA · EN 301 549 (v3.2.1) · Section 508 · European Accessibility Act

This report follows the VPAT 2.5 (ITI) layout. Conformance values are:
**Supports** · **Partially Supports** · **Does Not Support** · **Not Applicable** · **Not Evaluated**.

## Table 1 & 2: WCAG 2.1 Level A and AA

| Success Criterion | Conformance Level | Remarks and Explanations |
| --- | --- | --- |
${WCAG_CRITERIA.map(([n, name, level]) => row(n, name, level)).join("\n")}

## EN 301 549 — additional clauses to confirm

| Clause | Requirement | Conformance | Remarks |
| --- | --- | --- | --- |
| 5.2 | Activation of accessibility features | Not Evaluated | |
| 7.x | Video captions / audio description (if media) | Not Evaluated | |
| 11.x | Software (web app) — maps to WCAG above | See Table above | |
| 12.1.1 | Accessibility and compatibility features documented | Not Evaluated | |
| 12.2 | Accessible documentation and support | Not Evaluated | |

_Fill the Conformance and Remarks columns from the run's accessibility findings. Generated by GLV Infotech testing-agent; have a person review before it is given to a customer or a procurement body._
`;
}

